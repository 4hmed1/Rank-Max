import type { CheckResult } from "./types.js";

export function buildHtmlDashboard(report: {
  url: string;
  score: number;
  grade: string;
  responseTimeMs: number;
  results: CheckResult[];
}): string {
  const color = report.score >= 80 ? "#10b981" : report.score >= 55 ? "#f59e0b" : "#ef4444";
  const rows = report.results
    .map(
      (r) => `
      <div class="card ${r.passed ? "pass" : "fail"}">
        <div class="row">
          <span class="badge">${r.passed ? "PASS" : "FIX"}</span>
          <strong>${r.name}</strong>
          <span class="pts">${r.weight} pts</span>
        </div>
        <p class="why">${r.why}</p>
        ${!r.passed ? `<p class="fix"><strong>Action:</strong> ${r.fix}</p>` : ""}
      </div>`
    )
    .join("");

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <title>Rank Max AI-Readiness Report — ${report.url}</title>
  <style>
    body { font-family: system-ui, -apple-system, sans-serif; background: #09090b; color: #fafafa; margin: 0; padding: 2rem; }
    .container { max-width: 860px; margin: 0 auto; }
    .header { display: flex; justify-content: space-between; align-items: center; border-bottom: 1px solid #27272a; padding-bottom: 1.5rem; margin-bottom: 2rem; }
    .score-box { text-align: right; }
    .score { font-size: 3rem; font-weight: 800; color: ${color}; line-height: 1; }
    .meta { color: #a1a1aa; font-size: 0.9rem; margin-top: 0.35rem; }
    .card { background: #18181b; border: 1px solid #27272a; border-left: 4px solid #10b981; border-radius: 10px; padding: 1rem 1.25rem; margin-bottom: 0.85rem; }
    .card.fail { border-left-color: #ef4444; }
    .row { display: flex; align-items: center; gap: 0.75rem; }
    .badge { font-size: 0.72rem; font-weight: 700; padding: 0.2rem 0.5rem; border-radius: 999px; background: #064e3b; color: #6ee7b7; }
    .fail .badge { background: #7f1d1d; color: #fca5a5; }
    .pts { margin-left: auto; color: #71717a; font-size: 0.85rem; }
    .why { color: #a1a1aa; font-size: 0.9rem; margin: 0.5rem 0 0; }
    .fix { color: #fde047; font-size: 0.9rem; margin: 0.4rem 0 0; }
    footer { text-align: center; color: #71717a; margin-top: 2.5rem; font-size: 0.85rem; }
  </style>
</head>
<body>
  <div class="container">
    <div class="header">
      <div>
        <div style="color:#38bdf8;font-weight:700;letter-spacing:0.08em;font-size:0.8rem;">RANK MAX · SEO · AEO · GEO ENGINE</div>
        <h1 style="margin:0.3rem 0;font-size:1.5rem;">${report.url}</h1>
        <div class="meta">Response Latency: ${report.responseTimeMs}ms · Grade: <strong>${report.grade}</strong></div>
      </div>
      <div class="score-box">
        <div class="score">${report.score}/100</div>
        <div class="meta">AI-Readiness Score</div>
      </div>
    </div>
    ${rows}
    <footer>Generated by <strong>Rank Max CLI</strong> · Engineered by Max Digital Studio</footer>
  </div>
</body>
</html>`;
}
